"""Filtering, sorting, rendering and saving of checked proxies. No dependency on the rest of the tool."""
from __future__ import annotations

import csv
import io
import json
import re
import time
from pathlib import Path
from urllib.parse import quote

ANON_RANK = {"elite": 0, "anonymous": 1, "transparent": 2, "unknown": 3}

SORT_PRESETS = {
    "latency": "Fastest first",
    "anonymity": "Anonymity, then speed",
    "country": "Country, then anonymity, then speed",
    "anon_country": "Anonymity, then country, then speed",
    "throughput": "Download speed",
}

# id -> (label, extension, filename suffix)
FORMATS = {
    "url": ("proto://ip:port", "txt", ""),
    "hostport": ("ip:port", "txt", "-ipport"),
    "proxychains": ("proxychains config", "conf", "-proxychains"),
    "pac": ("Browser PAC file", "pac", ""),
    "csv": ("CSV", "csv", ""),
    "json": ("JSON", "json", ""),
    "template": ("Custom template", "txt", "-custom"),
}

CSV_COLUMNS = ["url", "proto", "host", "port", "latency_ms", "anonymity", "https", "country", "city", "asn", "org",
               "exit_ip", "speed_mbps", "auth"]


def _key(preset: str):
    rank = lambda r: ANON_RANK.get(r.anonymity, 9)
    if preset == "anonymity":
        return lambda r: (rank(r), r.latency_ms)
    if preset == "country":
        return lambda r: (r.country, rank(r), r.latency_ms)
    if preset == "anon_country":
        return lambda r: (rank(r), r.country, r.latency_ms)
    if preset == "throughput":
        return lambda r: (-(r.speed_mbps or -1), r.latency_ms)
    return lambda r: r.latency_ms


def sort_results(rows, preset: str) -> list:
    return sorted(rows, key=_key(preset))


def select(rows, f: dict) -> list:
    protos, anons = set(f.get("protocols") or []), set(f.get("anonymity") or [])
    countries = {c.upper() for c in f.get("countries") or []}
    max_ms = f.get("max_latency") or 0
    https_only = bool(f.get("https_only"))
    out = [r for r in rows
           if (not protos or r.proto in protos) and (not anons or r.anonymity in anons)
           and (not countries or r.country in countries) and (not max_ms or r.latency_ms <= max_ms)
           and (not https_only or r.https)]
    return out


class _Safe(dict):
    def __missing__(self, key):
        return "{" + key + "}"


def _login(r, user: str, pw: str) -> tuple[str, str]:
    """The login to write for a proxy: the one typed in the save options, else the proxy's own."""
    if user:
        return user, pw
    if getattr(r, "auth", ""):
        u, _, p = r.auth.partition(":")
        return u, p
    return "", ""


def render(rows, fmt: str, *, template: str = "{proto}://{host}:{port}", user: str = "", pw: str = "",
           pac_max: int = 20) -> str:
    rows = list(rows)
    if fmt == "url":
        out = []
        for r in rows:
            u, p = _login(r, user, pw)
            out.append(f"{r.proto}://{quote(u, safe='')}:{quote(p, safe='')}@{r.host}:{r.port}" if u
                       else f"{r.proto}://{r.host}:{r.port}")
        return "\n".join(out)
    if fmt == "hostport":
        out = []
        for r in rows:
            u, p = _login(r, user, pw)
            out.append(f"{u}:{p}@{r.host}:{r.port}" if u else f"{r.host}:{r.port}")
        return "\n".join(out)
    if fmt == "proxychains":
        lines = ["# proxychains list, fastest first. Paste under [ProxyList] in proxychains.conf", "[ProxyList]"]
        for r in rows:
            u, p = _login(r, user, pw)
            lines.append(f"{r.proto} {r.host} {r.port}" + (f" {u} {p}" if u else ""))
        return "\n".join(lines)
    if fmt == "pac":
        kind = {"http": "PROXY", "socks4": "SOCKS", "socks5": "SOCKS5"}
        chain = "; ".join(f"{kind[r.proto]} {r.host}:{r.port}" for r in rows[:pac_max])
        return ("// Generated by ProxyHive. Tries the proxies in order. There is deliberately no DIRECT\n"
                "// fallback, so traffic never silently leaves through your real IP.\n"
                f'function FindProxyForURL(url, host) {{\n  return "{chain}";\n}}\n')
    if fmt == "csv":
        buf = io.StringIO()
        w = csv.writer(buf)
        w.writerow(CSV_COLUMNS)
        for r in rows:
            w.writerow([r.url, r.proto, r.host, r.port, r.latency_ms, r.anonymity, r.https, r.country, r.city,
                        r.asn, r.org, r.exit_ip, "" if r.speed_mbps is None else r.speed_mbps, r.auth])
        return buf.getvalue()
    if fmt == "json":
        return json.dumps([{**r.as_dict(secret=True), "url": r.url} for r in rows], indent=2)
    if fmt == "template":
        out = []
        for r in rows:
            u, p = _login(r, user, pw)
            fields = _Safe(proto=r.proto, host=r.host, port=r.port, user=u, country=r.country, city=r.city,
                           asn=r.asn, org=r.org, https=r.https, latency=r.latency_ms, anonymity=r.anonymity,
                           speed=r.speed_mbps or "", url=r.url, auth=r.auth)
            fields["pass"] = p
            out.append(template.format_map(fields))
        return "\n".join(out)
    raise ValueError(f"unknown format: {fmt}")


def _safe_name(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]", "_", s)[:80] or "proxies"


def resolve_dir(path: str, base: Path) -> Path:
    p = Path(path).expanduser() if path else Path("results")
    return p if p.is_absolute() else base / p


def save_files(rows, cfg: dict, base: Path) -> list[Path]:
    """Write `rows` according to the save settings. Returns the files written."""
    rows = sort_results(select(rows, cfg["filters"]), cfg["sort"])
    if cfg["filters"].get("max_count"):
        rows = rows[: cfg["filters"]["max_count"]]
    if not rows:
        return []
    out_dir = resolve_dir(cfg["dir"], base)
    out_dir.mkdir(parents=True, exist_ok=True)
    attr = {"protocol": "proto", "country": "country", "anonymity": "anonymity"}.get(cfg["split"])
    groups: dict[str, list] = {}
    for r in rows:
        groups.setdefault(_safe_name(getattr(r, attr)) if attr else "", []).append(r)
    stamp = time.strftime("_%Y%m%d-%H%M%S") if cfg["timestamp"] else ""
    prefix = _safe_name(cfg["prefix"])
    written = []
    for group, grows in groups.items():
        for fmt in cfg["formats"]:
            _, ext, suffix = FORMATS[fmt]
            path = out_dir / f"{prefix}{stamp}{'_' + group if group else ''}{suffix}.{ext}"
            path.write_text(render(grows, fmt, template=cfg["template"], user=cfg["user"], pw=cfg["pass"]),
                            encoding="utf-8")
            written.append(path)
    return written
